// Real menu flow without ?autoplay: intro -> character select -> begin -> binder -> close -> pause -> resume.
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--ignore-gpu-blocklist', '--use-angle=metal'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => {
  if (m.type() === 'error') errors.push(m.text());
  if (m.text().startsWith('[game]') || m.text().startsWith('[input]')) console.log('  ', m.text());
});
await page.goto(process.env.URL ?? 'http://localhost:5174/');
await page.waitForFunction(() => window.__isle?.ready === true, null, { timeout: 60000 });
await page.waitForTimeout(2500);
await page.waitForFunction(() => window.__isle?.ready === true, null, { timeout: 60000 });
const mode = () => page.evaluate(() => window.__isle.state().mode);
const visible = (sel) => page.evaluate((s) => { const el = document.querySelector(s); return !!el && !el.classList.contains('hidden') && getComputedStyle(el).display !== 'none'; }, sel);
const log = async (label) => console.log(`${label.padEnd(26)} mode=${await mode()} intro=${await visible('.overlay.intro')} select=${await visible('.overlay.select')} hud=${await visible('.hud')} binder=${await visible('.overlay.binder')} pause=${await visible('.overlay.pause')}`);
await log('loaded');
await page.click('.overlay.intro .enter');
await page.waitForFunction(() => { const c = window.__isle.character(); return c.wearing === c.picked; }, null, { timeout: 60000 });
await log('after Enter the Isle');
await page.click('.pick[data-id="momo"]');
await page.waitForFunction(() => window.__isle.character().wearing === 'momo', null, { timeout: 60000 });
console.log(`picked momo               begin enabled=${await page.evaluate(() => !document.querySelector('.overlay.select .begin').disabled)} perks.wardDuration=${await page.evaluate(() => window.__isle.character().perks.wardDuration)}`);
await page.fill('.overlay.select .sel-input', '  Yan  ');
await page.click('.overlay.select .begin');
await page.waitForTimeout(800);
await log('after Begin');
const shown = await page.evaluate(() => ({ corner: document.querySelector('.player-name').textContent, tag: document.querySelector('.nameplate span').textContent, tagAlpha: Number(document.querySelector('.nameplate').style.opacity) }));
console.log(`name shown                 corner="${shown.corner}" tag="${shown.tag}" tag opacity=${shown.tagAlpha}`);
if (shown.corner !== 'Yan' || shown.tag !== 'Yan' || !(shown.tagAlpha > 0)) errors.push(`name not shown right: ${JSON.stringify(shown)}`);
const savedName = await page.evaluate(() => localStorage.getItem('wildcard-isle:name'));
if (savedName !== 'Yan') errors.push(`name not saved (got ${savedName})`);
const saved = await page.evaluate(() => localStorage.getItem('wildcard-isle:character'));
if (saved !== 'momo') errors.push(`character not saved (got ${saved})`);
await page.keyboard.press('Tab');
await page.waitForTimeout(300);
await log('after Tab');
await page.click('.overlay.binder .close');
await page.waitForTimeout(300);
await log('after Close');
await page.evaluate(() => document.exitPointerLock());
await page.waitForTimeout(300);
await log('pointer lock released (Esc)');
await page.click('.resume');
await page.waitForTimeout(300);
await log('after Resume');
await browser.close();
console.log(errors.length ? `errors:\n - ${errors.join('\n - ')}` : 'no console errors');
process.exit(errors.length ? 1 : 0);
